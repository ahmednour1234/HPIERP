1. Data Collection and Usage
Our Point of Sale (POS) system may collect certain data to enhance user experience and ensure the system operates efficiently. This includes:

Admin Location Tracking: We may collect the location of admin users to track the system's usage in real-time, provide insights on system operations, and enhance security.
Data Security: Location data is securely stored and is not shared with third parties except as required by law or to ensure the proper functioning of the system.
2. Bluetooth Permission for Printer Integration
To support seamless printing functionality, our system requests access to Bluetooth. This is used solely for:

Connecting with compatible printers for transaction receipts.
Ensuring smooth and efficient operation between the POS system and Bluetooth-enabled devices.
3. Compliance with Platform Policies
This app complies with Apple App Store and Google Play Store privacy requirements. Users will be explicitly asked to grant permissions for location tracking and Bluetooth access. These permissions are not mandatory for app usage but are required for certain functionalities:

Location tracking is essential for operational monitoring and security purposes.
Bluetooth access is required for integrating with printers.
4. User Control and Consent
Users have full control over granting or revoking these permissions:

Location access and Bluetooth permissions can be managed via device settings.
Disabling these permissions may limit certain features but will not affect the core functionality of the POS system.
5. Transparency and Updates
We are committed to transparency about how we collect, use, and protect your data. This privacy policy will be updated as needed to comply with regulations and improve user experience.

